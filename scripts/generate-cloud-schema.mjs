import { writeFile } from 'node:fs/promises'
import { createServer } from 'vite'
import { z } from 'zod'

// Generated from the same schema used by backup validation. Custom relational
// refinements are enforced separately by validate_finance_document in SQL.
const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false } })
try {
  const { appDataSchema } = await server.ssrLoadModule('/src/domain/budget/schema.ts')
  const schema = z.toJSONSchema(appDataSchema, { unrepresentable: 'any' })
  const sql = `-- Generated by node scripts/generate-cloud-schema.mjs\ncreate extension if not exists pg_jsonschema with schema extensions;\ncreate or replace function public.finance_document_schema() returns json\nlanguage sql immutable set search_path = ''\nas $schema$ select '${JSON.stringify(schema).replaceAll("'", "''")}'::json $schema$;\nrevoke all on function public.finance_document_schema() from public, anon, authenticated;\n`
  await writeFile('supabase/migrations/20261110123510_finance_schema.sql', sql)
} finally { await server.close() }
