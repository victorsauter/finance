// Applies the PowerSync database-side requirements to the LOCAL Supabase
// database, at runtime. Nothing goes into supabase/migrations.
//
//   1. a replication role (REPLICATION, BYPASSRLS, LOGIN) with SELECT on the
//      seven entity tables only;
//   2. a publication named `powersync` listing those seven tables only;
//   3. a bucket-storage role and a separate `powersync_storage` database on the
//      same server (Postgres 14+ allows source and storage on one server);
//   4. `.env` (gitignored) with the two connection strings, random passwords.
//
// wal_level is already `logical` on Supabase, so no server setting changes.
//
// Usage: npm run setup-db [-- <postgres connection string>]
// Default connection string: DB_URL from `supabase status`.
import { randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import pg from 'pg'
import { SPIKE_DIR, assertLocal, localSupabase } from '../src/env.ts'

const ENTITY_TABLES = [
  'budget_months',
  'budget_incomes',
  'budget_accounts',
  'budget_expense_categories',
  'budget_expense_items',
  'imported_transactions',
  'user_settings',
] as const

// Inside the Supabase Docker network the database is reachable by container name.
const DOCKER_DB_HOST = 'supabase_db_finance:5432'

async function main() {
  const dbUrl = process.argv[2] ?? localSupabase().dbUrl
  assertLocal(dbUrl, 'the database')

  const client = new pg.Client({ connectionString: dbUrl })
  await client.connect()
  const replicationPassword = randomBytes(18).toString('hex')
  const storagePassword = randomBytes(18).toString('hex')
  const tableList = ENTITY_TABLES.map((name) => `public.${name}`).join(', ')

  try {
    const { rows: walRows } = await client.query<{ wal_level: string }>('show wal_level')
    if (walRows[0].wal_level !== 'logical') {
      throw new Error(`wal_level is ${walRows[0].wal_level}; PowerSync needs logical. Change it in the Supabase config, not here.`)
    }

    // 1. Replication role. ALTER keeps the script re-runnable.
    const roleExists = await client.query("select 1 from pg_roles where rolname = 'powersync_role'")
    const roleVerb = roleExists.rowCount ? 'alter' : 'create'
    await client.query(
      `${roleVerb} role powersync_role with replication bypassrls login password '${replicationPassword}'`,
    )
    await client.query('grant usage on schema public to powersync_role')
    await client.query(`grant select on ${tableList} to powersync_role`)

    // 2. Publication (name fixed by PowerSync).
    const pubExists = await client.query("select 1 from pg_publication where pubname = 'powersync'")
    if (pubExists.rowCount) {
      await client.query(`alter publication powersync set table ${tableList}`)
    } else {
      await client.query(`create publication powersync for table ${tableList}`)
    }

    // 3. Bucket storage: its own role and database.
    const storageRoleExists = await client.query(
      "select 1 from pg_roles where rolname = 'powersync_storage_user'",
    )
    const storageVerb = storageRoleExists.rowCount ? 'alter' : 'create'
    await client.query(
      `${storageVerb} role powersync_storage_user with login password '${storagePassword}'`,
    )
    const dbExists = await client.query("select 1 from pg_database where datname = 'powersync_storage'")
    if (!dbExists.rowCount) {
      // `postgres` is not a superuser on Supabase: it must be a member of the
      // owner role to create a database owned by it.
      await client.query('grant powersync_storage_user to postgres')
      await client.query('create database powersync_storage owner powersync_storage_user')
    }
  } finally {
    await client.end()
  }

  const envFile = path.join(SPIKE_DIR, '.env')
  writeFileSync(
    envFile,
    [
      '# Generated by scripts/setup-db.ts. Local only, gitignored. Do not commit.',
      `PS_DATA_SOURCE_URI=postgresql://powersync_role:${replicationPassword}@${DOCKER_DB_HOST}/postgres`,
      `PS_STORAGE_SOURCE_URI=postgresql://powersync_storage_user:${storagePassword}@${DOCKER_DB_HOST}/powersync_storage`,
      '',
    ].join('\n'),
    { mode: 0o600 },
  )
  console.log(`Database ready: role powersync_role, publication powersync (${ENTITY_TABLES.length} tables), database powersync_storage.`)
  console.log(`Wrote ${path.relative(process.cwd(), envFile) || envFile}`)
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
